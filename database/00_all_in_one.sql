DROP DATABASE IF EXISTS legalease_eproject;
CREATE DATABASE legalease_eproject CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE legalease_eproject;

CREATE TABLE users (
  id INT AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(150) NOT NULL,
  email VARCHAR(150) NOT NULL UNIQUE,
  password VARCHAR(255) NOT NULL,
  role ENUM('admin','lawyer','customer') NOT NULL,
  is_active TINYINT(1) NOT NULL DEFAULT 1,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE password_reset_tokens (
 id INT AUTO_INCREMENT PRIMARY KEY,user_id INT NOT NULL,token_hash CHAR(64) NOT NULL UNIQUE,expires_at DATETIME NOT NULL,used_at DATETIME NULL,created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_reset_user FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE email_outbox (
 id INT AUTO_INCREMENT PRIMARY KEY,recipient VARCHAR(190) NOT NULL,subject VARCHAR(255) NOT NULL,body TEXT NOT NULL,delivery_status ENUM('Queued','Sent','Failed') NOT NULL DEFAULT 'Queued',created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE locations (id INT AUTO_INCREMENT PRIMARY KEY, city_name VARCHAR(100) NOT NULL UNIQUE) ENGINE=InnoDB;
CREATE TABLE specializations (id INT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(120) NOT NULL UNIQUE) ENGINE=InnoDB;
CREATE TABLE customer_profiles (
 id INT AUTO_INCREMENT PRIMARY KEY,user_id INT NOT NULL UNIQUE,full_name VARCHAR(150) NOT NULL,phone VARCHAR(30) DEFAULT '',address VARCHAR(255) DEFAULT '',avatar_file VARCHAR(255) DEFAULT '',gender ENUM('Male','Female','Other') NULL,birth_date DATE NULL,
 CONSTRAINT fk_customer_user FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE lawyer_profiles (
 id INT AUTO_INCREMENT PRIMARY KEY,user_id INT NOT NULL UNIQUE,full_name VARCHAR(150) NOT NULL,phone VARCHAR(30) DEFAULT '',experience_years INT NOT NULL DEFAULT 0,bio TEXT,
 office_address VARCHAR(255) DEFAULT '',location_id INT NULL,is_verified TINYINT(1) NOT NULL DEFAULT 0,rating DECIMAL(2,1) NOT NULL DEFAULT 0.0,
 consultation_fee DECIMAL(10,2) NOT NULL DEFAULT 500000,avatar_file VARCHAR(255) DEFAULT '',created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_lawyer_user FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE,
 CONSTRAINT fk_lawyer_location FOREIGN KEY(location_id) REFERENCES locations(id) ON DELETE SET NULL
) ENGINE=InnoDB;
CREATE TABLE lawyer_specialties (
 lawyer_id INT NOT NULL,specialization_id INT NOT NULL,PRIMARY KEY(lawyer_id,specialization_id),
 CONSTRAINT fk_ls_lawyer FOREIGN KEY(lawyer_id) REFERENCES lawyer_profiles(id) ON DELETE CASCADE,
 CONSTRAINT fk_ls_spec FOREIGN KEY(specialization_id) REFERENCES specializations(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE lawyer_verifications (
 id INT AUTO_INCREMENT PRIMARY KEY,lawyer_id INT NOT NULL UNIQUE,id_card_number VARCHAR(30) NOT NULL DEFAULT '',license_number VARCHAR(100) NOT NULL,document_file VARCHAR(1000) DEFAULT '',
 status ENUM('Pending','Approved','Rejected') NOT NULL DEFAULT 'Pending',admin_note VARCHAR(255) DEFAULT NULL,reviewed_by INT NULL,reviewed_at DATETIME NULL,created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_ver_lawyer FOREIGN KEY(lawyer_id) REFERENCES lawyer_profiles(id) ON DELETE CASCADE,
 CONSTRAINT fk_ver_admin FOREIGN KEY(reviewed_by) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB;
CREATE TABLE availability_slots (
 id INT AUTO_INCREMENT PRIMARY KEY,lawyer_id INT NOT NULL,available_date DATE NOT NULL,start_time TIME NOT NULL,end_time TIME NOT NULL,is_available TINYINT(1) NOT NULL DEFAULT 1,created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX idx_slot_lawyer_date(lawyer_id,available_date),CONSTRAINT fk_slot_lawyer FOREIGN KEY(lawyer_id) REFERENCES lawyer_profiles(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE appointments (
 id INT AUTO_INCREMENT PRIMARY KEY,slot_id INT NOT NULL,customer_id INT NOT NULL,lawyer_id INT NOT NULL,service_name VARCHAR(150) DEFAULT 'Legal Consultation',note TEXT NOT NULL,
 appointment_date DATE NOT NULL,start_time TIME NOT NULL,end_time TIME NOT NULL,fee DECIMAL(10,2) NOT NULL DEFAULT 0,status ENUM('Pending','Confirmed','Completed','Cancelled') NOT NULL DEFAULT 'Pending',notes TEXT DEFAULT NULL,
 cancel_reason VARCHAR(255) DEFAULT NULL,cancelled_by ENUM('customer','lawyer','admin') DEFAULT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,updated_at DATETIME NULL,payment_due_at DATETIME NULL,payment_reminder_sent_at DATETIME NULL,INDEX idx_appt_lawyer_status(lawyer_id,status),INDEX idx_appt_customer_status(customer_id,status),
 CONSTRAINT fk_appt_slot FOREIGN KEY(slot_id) REFERENCES availability_slots(id),CONSTRAINT fk_appt_customer FOREIGN KEY(customer_id) REFERENCES customer_profiles(id) ON DELETE CASCADE,
 CONSTRAINT fk_appt_lawyer FOREIGN KEY(lawyer_id) REFERENCES lawyer_profiles(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE payments (
 id INT AUTO_INCREMENT PRIMARY KEY,appointment_id INT NOT NULL UNIQUE,customer_id INT NOT NULL,lawyer_id INT NOT NULL,amount DECIMAL(10,2) NOT NULL DEFAULT 0,method VARCHAR(50) DEFAULT '',
 status ENUM('Pending','Success','Cancelled','Failed','Refund Pending','Refunded','Partially Refunded') NOT NULL DEFAULT 'Pending',created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,paid_at DATETIME NULL,updated_at DATETIME NULL,
 CONSTRAINT fk_payment_appt FOREIGN KEY(appointment_id) REFERENCES appointments(id) ON DELETE CASCADE,
 CONSTRAINT fk_payment_customer FOREIGN KEY(customer_id) REFERENCES customer_profiles(id) ON DELETE CASCADE,
 CONSTRAINT fk_payment_lawyer FOREIGN KEY(lawyer_id) REFERENCES lawyer_profiles(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE refunds (
 id INT AUTO_INCREMENT PRIMARY KEY,payment_id INT NOT NULL UNIQUE,appointment_id INT NOT NULL,customer_id INT NOT NULL,original_amount DECIMAL(10,2) NOT NULL,cancellation_fee DECIMAL(10,2) NOT NULL DEFAULT 0,refund_amount DECIMAL(10,2) NOT NULL DEFAULT 0,lawyer_compensation DECIMAL(10,2) NOT NULL DEFAULT 0,platform_fee DECIMAL(10,2) NOT NULL DEFAULT 0,status ENUM('Pending','Processed','Failed') NOT NULL DEFAULT 'Pending',reason VARCHAR(255) DEFAULT 'Appointment cancellation',processed_at DATETIME NULL,created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_refund_payment FOREIGN KEY(payment_id) REFERENCES payments(id) ON DELETE CASCADE,
 CONSTRAINT fk_refund_appointment FOREIGN KEY(appointment_id) REFERENCES appointments(id) ON DELETE CASCADE,
 CONSTRAINT fk_refund_customer FOREIGN KEY(customer_id) REFERENCES customer_profiles(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE reviews (
 id INT AUTO_INCREMENT PRIMARY KEY,appointment_id INT NULL UNIQUE,lawyer_id INT NULL,user_id INT NULL,rating INT NOT NULL,comment TEXT NULL,created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_review_appt FOREIGN KEY(appointment_id) REFERENCES appointments(id) ON DELETE CASCADE,
 CONSTRAINT fk_review_lawyer FOREIGN KEY(lawyer_id) REFERENCES lawyer_profiles(id) ON DELETE CASCADE,
 CONSTRAINT fk_review_user FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE notifications (
 id INT AUTO_INCREMENT PRIMARY KEY,user_id INT NOT NULL,message TEXT NOT NULL,type ENUM('System','Email','Reminder') NOT NULL DEFAULT 'System',link_url VARCHAR(255) NULL,is_read TINYINT(1) NOT NULL DEFAULT 0,created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_notification_user FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE qa_questions (
 id INT AUTO_INCREMENT PRIMARY KEY,lawyer_id INT NOT NULL,customer_id INT NOT NULL,title VARCHAR(255) NOT NULL,question TEXT NOT NULL,answer TEXT NULL,status ENUM('New','Answered') NOT NULL DEFAULT 'New',created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,answered_at DATETIME NULL,
 CONSTRAINT fk_qa_lawyer FOREIGN KEY(lawyer_id) REFERENCES lawyer_profiles(id) ON DELETE CASCADE,CONSTRAINT fk_qa_customer FOREIGN KEY(customer_id) REFERENCES customer_profiles(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE content_management (
 id INT AUTO_INCREMENT PRIMARY KEY,type ENUM('FAQ','Guide','News','Announcement') NOT NULL,category VARCHAR(100) DEFAULT NULL,title VARCHAR(255) NOT NULL,body TEXT NOT NULL,image_file VARCHAR(255) DEFAULT NULL,link_url VARCHAR(255) DEFAULT NULL,sort_order INT NOT NULL DEFAULT 0,created_by INT NOT NULL,is_published TINYINT(1) NOT NULL DEFAULT 1,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 CONSTRAINT fk_content_admin FOREIGN KEY(created_by) REFERENCES users(id)
) ENGINE=InnoDB;
CREATE TABLE site_content (id INT AUTO_INCREMENT PRIMARY KEY,content_key VARCHAR(100) NOT NULL UNIQUE,content_value TEXT NOT NULL,updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP) ENGINE=InnoDB;
CREATE TABLE system_audit_logs (id INT AUTO_INCREMENT PRIMARY KEY,admin_id INT NOT NULL,action VARCHAR(255) NOT NULL,created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,CONSTRAINT fk_audit_admin FOREIGN KEY(admin_id) REFERENCES users(id) ON DELETE CASCADE) ENGINE=InnoDB;

